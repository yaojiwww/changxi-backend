-- =============================================================================
-- 畅溪后端 — 刷题域初始化脚本
-- 对应代码：src/quiz_db.cj（数据访问）、src/quiz.cj（接口）
--
-- 执行方式：
--   sudo mariadb < sql/quiz.sql
--   （或进入 mariadb 客户端后执行：source sql/quiz.sql）
--
-- 可重复执行：建表用 IF NOT EXISTS，种子数据用 INSERT IGNORE + 显式主键，
-- 重复执行只会跳过已存在的行，不会插出重复题目。
-- =============================================================================

CREATE DATABASE IF NOT EXISTS `changxi`
  DEFAULT CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE `changxi`;

-- -----------------------------------------------------------------------------
-- 1. 章节表
-- 首期只有一个题库（保育员考证），所以不建"题库"表，章节直接挂在这一层。
-- 以后要加第二个证书时，在这一层之上加 subjects 表即可，questions 不用动。
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `chapters` (
  `id`         BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '章节ID',
  `name`       VARCHAR(100)    NOT NULL                COMMENT '章节名称',
  `sort_order` INT             NOT NULL DEFAULT 0      COMMENT '排序值，越小越靠前',
  `created_at` DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (`id`),
  KEY `idx_sort` (`sort_order`)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci
  COMMENT = '章节表';

-- -----------------------------------------------------------------------------
-- 2. 题目表
-- 注意这里没有"答案"字段 —— 正确答案由 question_options.is_correct 决定，
-- 单一来源，避免"答案列说 AB，选项表说 A"这种对不上的情况。
--   type: 1=单选题  2=多选题
-- 题干 analysis 是解析，答题时随判分结果一起返回，取题接口不下发。
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `questions` (
  `id`         BIGINT UNSIGNED NOT NULL COMMENT '题目ID',
  `chapter_id` BIGINT UNSIGNED NOT NULL COMMENT '所属章节ID',
  `type`       TINYINT         NOT NULL DEFAULT 1 COMMENT '题型：1单选 2多选',
  `stem`       TEXT            NOT NULL           COMMENT '题干',
  `analysis`   TEXT            NOT NULL           COMMENT '答案解析',
  `sort_order` INT             NOT NULL DEFAULT 0 COMMENT '章内排序值，越小越靠前',
  PRIMARY KEY (`id`),
  KEY `idx_chapter_sort` (`chapter_id`, `sort_order`),
  CONSTRAINT `fk_question_chapter` FOREIGN KEY (`chapter_id`) REFERENCES `chapters` (`id`)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci
  COMMENT = '题目表';

-- -----------------------------------------------------------------------------
-- 3. 选项表
-- 一道题 2~6 个选项，label 是 A/B/C/D 这类字母，前端按 sort_order 展示。
-- 多选题就有多行 is_correct = 1。
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `question_options` (
  `id`          BIGINT UNSIGNED NOT NULL COMMENT '选项ID',
  `question_id` BIGINT UNSIGNED NOT NULL COMMENT '所属题目ID',
  `label`       VARCHAR(4)      NOT NULL COMMENT '选项标号：A/B/C/D',
  `content`     VARCHAR(500)    NOT NULL COMMENT '选项内容',
  `is_correct`  TINYINT         NOT NULL DEFAULT 0 COMMENT '是否正确答案：1是 0否',
  `sort_order`  INT             NOT NULL DEFAULT 0 COMMENT '展示顺序',
  PRIMARY KEY (`id`),
  KEY `idx_question` (`question_id`, `sort_order`),
  CONSTRAINT `fk_option_question` FOREIGN KEY (`question_id`) REFERENCES `questions` (`id`)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci
  COMMENT = '题目选项表';

-- -----------------------------------------------------------------------------
-- 4. 答题记录表
-- 一行 = "某人对某题的最后一次作答"。用唯一索引 (user_id, question_id) 保证一人一题
-- 只有一行，重做时 ON DUPLICATE KEY UPDATE 覆盖，不会堆历史。
-- 这张表一次承担三件事：章节练习进度、答对统计、以后错题本的数据源。
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `user_answers` (
  `id`          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '记录ID',
  `user_id`     BIGINT UNSIGNED NOT NULL COMMENT '用户ID',
  `question_id` BIGINT UNSIGNED NOT NULL COMMENT '题目ID',
  `chapter_id`  BIGINT UNSIGNED NOT NULL COMMENT '冗余章节ID，按章节统计进度时免去 join 题目表',
  `my_answer`   VARCHAR(16)     NOT NULL DEFAULT '' COMMENT '我的作答，如 "A" 或 "ABD"，已归一化排序',
  `is_correct`  TINYINT         NOT NULL DEFAULT 0  COMMENT '是否答对：1是 0否',
  `answered_at` DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '作答时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_user_question` (`user_id`, `question_id`),
  KEY `idx_user_chapter` (`user_id`, `chapter_id`)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_unicode_ci
  COMMENT = '答题记录表';

